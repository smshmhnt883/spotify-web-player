import assert from 'node:assert/strict';
import { build } from 'esbuild';
const bundle = await build({entryPoints:['src/services/lyrics.ts'],bundle:true,platform:'node',format:'esm',write:false});
const {parseLrc,selectLyrics,fetchLyrics} = await import(`data:text/javascript;base64,${Buffer.from(bundle.outputFiles[0].text).toString('base64')}`);
assert.deepEqual(parseLrc('[offset:100]\n[00:02.50][00:04.005]Hello\n[00:05.00]\n[ar:Test]'),[{timeMs:2600,text:'Hello'},{timeMs:4105,text:'Hello'},{timeMs:5100,text:''}]);
const record={trackName:'Song',artistName:'Artist & Guest',duration:100,syncedLyrics:'[00:01.00]First\n[00:03.00]Second',plainLyrics:'First\nSecond'};
assert.equal(selectLyrics([record],'Song','Artist',100).mode,'synced');
assert.equal(selectLyrics([{...record,duration:91}],'Song','Artist',100).mode,'plain');
assert.equal(selectLyrics([{...record,syncedLyrics:'[00:01.00]First\n[02:00.00]Late'}],'Song','Artist',100).mode,'plain');
assert.equal(selectLyrics([{...record,artistName:'Someone Else'}],'Song','Artist',100).mode,'unavailable');
assert.equal(selectLyrics([{...record,trackName:'Song remix'}],'Song','Artist',100).mode,'unavailable');
assert.equal(selectLyrics([{...record,instrumental:true,syncedLyrics:null,plainLyrics:null}],'Song','Artist',100).mode,'instrumental');
assert.equal(selectLyrics([],'Song','Artist',100).mode,'unavailable');
assert.throws(()=>selectLyrics({},'Song','Artist',100));
